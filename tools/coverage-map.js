#!/usr/bin/env node
/* Behaviour-test coverage map (issue 901, plan §7e). Usage: node tools/coverage-map.js [--check]
   Writes docs/pds1/coverage.md (also a Stories column, #1037): one row per part (platform/components + platform/patterns), the §7e baseline items found in tests that name the part.
   Method: a test file counts for a part when it names the part as a whole PascalCase word; an item counts when that file holds its signal words.
   It is a signal map, not proof: a hit means a test touches the item, a gap means no test names it. --check fails when the file is stale. */
const fs = require('fs'), path = require('path');
const ITEMS = [
  ['render', /pageerror|console\.(error|warn)|consoleErrors|errors\.length|errors,\s*\[\]/],
  ['states', /aria-(disabled|invalid|busy|selected|expanded|checked|pressed|current)/],
  ['disabled', /disabled/i],
  ['keyboard', /keyboard|keydown|\.press\(|key:\s*['"](Enter|Tab| |Space|Escape|Arrow)/i],
  ['rtl', /\brtl\b|dir=["']rtl|dir\s*=\s*['"]rtl/i],
  ['long/empty', /long[- ]?text|overflow|empty|3\s*[×x]\s*(the )?English/i],
  ['axe', /\baxe\b|axe-core|axeCore/i],
  ['i18n', /locale|catalog|\bar-EG\b|\bar\.js\b|lang=["']ar/i],
];
const STATES = ['default', 'hover', 'focus', 'active', 'disabled', 'loading', 'error', 'selected'];
// the exported stories of a part and the DESIGN.md states they cover (a state word in a story's name, or its flag as an arg)
function stories(root, name) {
  const file = path.join(root, 'docs/site/stories', name + '.stories.tsx');
  if (!fs.existsSync(file)) return null;
  const src = fs.readFileSync(file, 'utf8'), names = [...src.matchAll(/^export const (\w+)/gm)].map((m) => m[1]);
  const text = names.join(' ').toLowerCase() + ' ' + [...src.matchAll(/\b(disabled|loading|selected|invalid|error)\s*:\s*true/g)].map((m) => m[1] === 'invalid' ? 'error' : m[1]).join(' ');
  return { count: names.length, states: STATES.filter((st) => text.includes(st) || (st === 'default' && names.length)) };
}
function build(root) {
  const parts = [];
  for (const kind of ['components', 'patterns']) {
    const dir = path.join(root, 'platform', kind);
    for (const n of fs.readdirSync(dir).sort()) if (fs.statSync(path.join(dir, n)).isDirectory()) parts.push({ name: n, kind: kind.slice(0, -1) });
  }
  const tdir = path.join(root, 'tests');
  const tests = fs.readdirSync(tdir).filter((f) => /test.*\.(js|cjs|mjs|ts)$/.test(f)).sort()
    .map((f) => ({ f, src: fs.readFileSync(path.join(tdir, f), 'utf8') }));
  const rows = parts.map((p) => {
    const re = new RegExp('(?<![A-Za-z0-9])' + p.name + '(?![a-z0-9])');
    const files = tests.filter((t) => re.test(t.src));
    const hit = ITEMS.map(([, rx]) => files.some((t) => rx.test(t.src)));
    return { ...p, files: files.map((t) => t.f), hit, stories: stories(root, p.name) };
  });
  const mark = (b) => (b ? 'Y' : '–');
  let out = '# Behaviour-test coverage map (plan §7e baseline)\n\n';
  out += 'Generated by `node tools/coverage-map.js`; do not edit by hand. `node tools/coverage-map.js --check` fails when this file is stale (never because stories are missing).\n\n';
  out += "- Y: a test file that names the part also holds the item's signal words. –: no such signal (a gap to check).\n";
  out += '- A signal map, not proof: it finds tests that touch an item, not that the item is fully tested. Family and DataGrid lists (§7e) are reviewed by hand in the gap issues.\n';
  out += '- Generic suites (tests/a11y.test.js runs axe over the whole catalog without naming each part) are not credited per part, so item 7 reads low; the gap issue asks for a per-part list.\n';
  out += '- Stories: the exported stories in docs/site/stories/<Part>.stories.tsx and the DESIGN.md states they cover; "none" when the file is missing (#1034).\n';
  out += '- Items: ' + ITEMS.map(([n], i) => (i + 1) + ' ' + n).join(' · ') + '.\n\n';
  const untested = rows.filter((r) => !r.files.length), full = rows.filter((r) => r.hit.every(Boolean)), withStories = rows.filter((r) => r.stories);
  out += `Summary: ${rows.length} parts · ${untested.length} with no test naming them · ${full.length} with all 8 signals · ${withStories.length} of ${rows.length} parts have stories.\n\n`;
  ITEMS.forEach(([n], i) => { out += `- Item ${i + 1} ${n}: ${rows.filter((r) => r.hit[i]).length}/${rows.length}\n`; });
  out += '\n| Part | Kind | Test files | ' + ITEMS.map((_, i) => i + 1).join(' | ') + ' | Stories | Missing |\n|---|---|---|' + ITEMS.map(() => '---').join('|') + '|---|---|\n';
  for (const r of rows) {
    const miss = ITEMS.filter((_, i) => !r.hit[i]).map(([n]) => n).join(', ');
    const st = r.stories ? `${r.stories.count} (${r.stories.states.join(', ') || 'no state'})` : 'none';
    out += `| ${r.name} | ${r.kind} | ${r.files.length} | ${r.hit.map(mark).join(' | ')} | ${st} | ${miss || 'none'} |\n`;
  }
  return out;
}
const stale = (root, out) => { const t = path.join(root, 'docs/pds1/coverage.md'); return !fs.existsSync(t) || fs.readFileSync(t, 'utf8') !== out; };
module.exports = { build, stale };
if (require.main === module) {
  const root = path.join(__dirname, '..'), out = build(root);
  if (process.argv.includes('--check')) {
    if (stale(root, out)) { console.error('coverage.md is stale: run node tools/coverage-map.js'); process.exit(1); }
    console.log('coverage.md is current');
  } else { fs.writeFileSync(path.join(root, 'docs/pds1/coverage.md'), out); console.log(out.split('\n').slice(6, 18).join('\n')); }
}
