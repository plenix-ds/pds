// The npm package's JavaScript (#709, Vite step 5): @plenix-ds/react's three builds of platform/index.ts, in Vite library
// mode. node build-packages.js runs Vite once per build (PLENIX_PACKAGE=<build>) and keeps everything else of the release:
// the package folders, package.json and the exports map, the copies, the styles, the CDN and the JSON API.
//   esm   release/packages/react/dist/: the ES modules, one per part (#685). An entry for each module platform/index.ts exports from,
//         at its own path (dist/components/Button/Button.js), plus the barrel (dist/index.js) and the Arabic opt-in
//         (dist/i18n/ar.js, #702). The code two parts share sits once in dist/chunks/, so an application that imports one
//         part bundles that part and what it uses.
//   cjs   release/packages/react/dist/index.cjs: the CommonJS build, one file
//   cdn   release/cdn/<version>/plenix.esm.js: the ES module as one file. Its banner gives it its own address
//         (const __plenixModuleUrl = import.meta.url, #284), so Icon finds the icon files beside it, whatever it is called.
// Run alone: PLENIX_PACKAGE=esm npx vite build --config vite.packages.config.mjs (cjs, cdn): it writes into the same
// ignored folders (release/), which node build-packages.js clears first.
//
// What it keeps from the old esbuild builds:
//   - react, react-dom, react-dom/client and react/jsx-runtime stay imports (peer dependencies); everything else is bundled
//   - the classic JSX runtime (React.createElement), target es2019, no minifying, no source map
//   - process.env.NODE_ENV stays as written (Vite's library mode leaves it to the application's bundler)
//   - icon modules (plenix-platform/icons/<set>/<name>) through the Platform config's plenix-icons plugin
//   - the banner on every file: '@plenix-ds/react <version> · ... (generated)' (Rollup's output.banner)
// What loads only when asked, in the ES modules only (#702): the CommonJS build and plenix.esm.js keep both built in.
//   Arabic: LocaleProvider's import of ../i18n/ar.js resolves to tools/npm-esm/ar.js, an empty catalog that
//     dist/i18n/ar.js fills (resolve.alias)
//   the icon names: Icon's import of ./library.ts resolves to tools/npm-esm/library.js, empty tables with loadNames()
//     (resolve.alias); the tables themselves (the Plenix names, symbols and mirrored symbols, and the Material library's
//     names) are the chunk icon-names, loaded the first time an Icon meets a name (#882; the library list alone since #702)
// The one plugin, plenix-icon-names, writes that chunk: glyphs.js (generated by build-icons.js) holds the tables as lines
// beside LIBRARY_COMMIT, which Icon needs at once, and no alias or resolve option can load some exports of a module as a
// module of its own.
// It also checks that the two aliases were reached only from LocaleProvider and Icon, so a new file that happens to import
// a module by the same relative name fails the build instead of getting the empty stand-in.
import path from 'node:path';
import fs from 'node:fs';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import { defineConfig } from 'vite';
import { plenixIcons } from './vite.platform.config.mjs';

const ROOT = path.dirname(fileURLToPath(import.meta.url));
const require = createRequire(import.meta.url);
const P = path.join(ROOT, 'platform');
const VERSION = require('./package.json').version;
const SCOPE = '@plenix-ds';
const BANNER = '/* ' + SCOPE + '/react ' + VERSION + ' · Plenix Platform components and patterns (generated) */';
const EXTERNAL = ['react', 'react-dom', 'react-dom/client', 'react/jsx-runtime'];
const OPT = path.join(ROOT, 'tools', 'npm-esm');
const ICON_NAMES = path.join(OPT, 'icon-names.js');
// the module each stand-in replaces, and the only file that may import it
const STAND_INS = [
  { file: path.join(OPT, 'ar.js'), importer: path.join(P, 'providers', 'LocaleProvider.tsx') },
  { file: path.join(OPT, 'library.js'), importer: path.join(P, 'components', 'Icon', 'Icon.tsx') },
];

// the part entries: platform/index.ts, each module it exports from (by its path under platform/, without the extension),
// and the Arabic opt-in
function partEntries() {
  const entries = { index: path.join(P, 'index.ts') };
  for (const m of fs.readFileSync(path.join(P, 'index.ts'), 'utf8').matchAll(/from '\.\/([^']+)'/g)) entries[m[1].replace(/\.[jt]sx?$/, '')] = path.join(P, m[1]);
  entries['i18n/ar'] = path.join(P, 'i18n', 'ar.optin.ts');
  return entries;
}

const iconNames = {
  name: 'plenix-icon-names',
  enforce: 'pre',
  resolveId(spec, importer) {
    return importer === STAND_INS[1].file && spec === './icon-names.js' ? ICON_NAMES : null;
  },
  load(id) {
    if (id !== ICON_NAMES) return null;
    const glyphs = fs.readFileSync(path.join(P, 'components', 'Icon', 'glyphs.js'), 'utf8');
    const lines = ['SYMBOLS', 'NAMES', 'MIRRORED', 'LIBRARY'].map((name) => {
      const line = new RegExp('^export const ' + name + ' = .*$', 'm').exec(glyphs);
      if (!line) this.error('platform/components/Icon/glyphs.js has no ' + name + ' line: run node build-app.js');
      return line[0];
    });
    return lines.join('\n') + '\n';
  },
  buildEnd(error) {
    if (error) return;
    for (const s of STAND_INS) {
      const info = this.getModuleInfo(s.file);
      const importers = info ? info.importers : [];
      if (importers.length !== 1 || importers[0] !== s.importer) this.error(path.relative(ROOT, s.file) + ' is imported by ' + (importers.map((f) => path.relative(ROOT, f)).join(', ') || 'nothing') + ', not only by ' + path.relative(ROOT, s.importer));
    }
  },
};

const BUILDS = {
  esm: { entry: partEntries, outDir: path.join(ROOT, 'release', 'packages', 'react', 'dist'), optional: true },
  cjs: { entry: () => path.join(P, 'index.ts'), outDir: path.join(ROOT, 'release', 'packages', 'react', 'dist'), format: 'cjs', file: 'index.cjs' },
  cdn: { entry: () => path.join(P, 'index.ts'), outDir: path.join(ROOT, 'release', 'cdn', VERSION), format: 'es', file: 'plenix.esm.js', banner: BANNER + '\nconst __plenixModuleUrl = import.meta.url;' },
  // the CDN's plenix-ar.js (issue 882): the built-in Arabic words, for an Arabic page that loads the CDN's plenix.js
  ar: { entry: () => path.join(P, 'i18n', 'ar.global.ts'), outDir: path.join(ROOT, 'release', 'cdn', VERSION), format: 'iife', file: 'plenix-ar.js', banner: '/* ' + SCOPE + ' ' + VERSION + ' · plenix-ar.js: Plenix\'s built-in Arabic words, after plenix.js (generated) */' },
};

export function packageConfig(name, overrides = {}) {
  const b = BUILDS[name];
  if (!b) throw new Error('No package build named ' + name + ' (one of: ' + Object.keys(BUILDS).join(', ') + ')');
  return {
    root: ROOT,
    configFile: false,
    publicDir: false,
    logLevel: 'warn',
    plugins: b.optional ? [plenixIcons, iconNames] : [plenixIcons],
    resolve: b.optional ? { alias: [
      { find: /^\.\.\/i18n\/ar\.js$/, replacement: STAND_INS[0].file },
      { find: /^\.\/library\.ts$/, replacement: STAND_INS[1].file },
    ] } : {},
    // every module, the bundled packages included, is lowered to es2019 as it is read (the old builds' target), so the
    // output needs no final esbuild pass (build.target 'esnext'): that pass drops the banner comment
    // the release, as Plenix's version export (#842, platform/version.ts)
    // the CDN's whole-file module is imported without a bundler too, so its process.env.NODE_ENV reads are "production"
    // (#1274); the npm builds leave them to the app's bundler
    define: Object.assign({ __PLENIX_VERSION__: JSON.stringify(VERSION) }, name === 'cdn' ? { 'process.env.NODE_ENV': JSON.stringify('production') } : {}),
    esbuild: { include: /\.[cm]?[jt]sx?$/, exclude: [], charset: 'ascii', target: 'es2019', jsx: 'transform', jsxFactory: 'React.createElement', jsxFragment: 'React.Fragment' },
    build: Object.assign({
      outDir: b.outDir,
      emptyOutDir: false,
      minify: false,
      sourcemap: false,
      target: 'esnext',
      reportCompressedSize: false,
      lib: b.optional
        ? { entry: b.entry(), formats: ['es'], fileName: (format, entryName) => entryName + '.js' }
        : { entry: b.entry(), formats: [b.format], fileName: () => b.file, name: 'PlenixLanguage' },
      rollupOptions: {
        external: EXTERNAL,
        output: b.optional
          ? { banner: BANNER, chunkFileNames: 'chunks/[name]-[hash].js' }
          : { banner: b.banner || BANNER, inlineDynamicImports: true },
      },
    }, overrides),
  };
}

// The CDN's per-screen modules (ADR 0052, #1208, #1293): release/cdn/<version>/esm/. One entry per public export (a file
// that re-exports its name from a chunk), the barrel index.js and the Arabic opt-in i18n/ar.js, over a few large chunks,
// so a screen loads a handful of files, not hundreds (CTM's 45-part shell: 7, was 214). The npm package's modules (the esm
// build above) keep one module per part, for bundlers.
// The chunks are layers (LAYERS below), from the import graph: each takes the code its parts reach through static imports
// that no earlier layer holds. What a part reaches, its imports reach too, so a layer imports only itself or an earlier
// one and no two chunks import each other. A data screen (ThemeProvider, Button, Dialog, DataGrid) loads core and grid
// only. The rest (rarer parts, page templates, commerce) is chunked by Rollup, so each loads only what it uses; a module
// only a dynamic import() reaches loads on first use (#1145).
// process.env.NODE_ENV is "production": a page without a bundler has no process (#1264).
const ENTRY = 'plenix-entry:';
// The layers, in order (G3 on #1293): what every screen needs (the theme, buttons, dialogs), the data grid (CTM's
// screens and most apps draw one), the app shell, the form controls, the charts. Each is the code its parts reach that no earlier layer holds.
const LAYERS = [
  ['core', ['ThemeProvider', 'Button', 'Dialog']],
  ['grid', ['DataGrid']],
  ['shell', ['AppShell', 'AppHeader', 'NavPane', 'NavList', 'CommandBar', 'CommandBarSearch', 'ToolRail', 'Toolbar', 'SecondaryPane', 'SplitView', 'ReadingPane', 'PagePanes', 'PageContent', 'PageHeader', 'Menu', 'MenuBar', 'Tabs', 'Panel', 'Card', 'Stack', 'Inline', 'Center', 'Text', 'Heading', 'Notice', 'EmptyState', 'LoadingState', 'ToastProvider', 'DirectionProvider', 'Icon', 'Image', 'List', 'Tooltip', 'Badge']],
  ['forms', ['Field', 'Input', 'Textarea', 'Select', 'Combobox', 'Checkbox', 'RadioGroup', 'Switch', 'DatePicker', 'NumberInput', 'SearchField', 'Form', 'FilterPanel']],
  ['charts', ['BarChart', 'LineChart', 'AreaChart', 'PieChart', 'DonutChart', 'ChartFrame', 'Gauge']],
];
export function cdnEsmConfig() {
  const names = [];
  for (const m of fs.readFileSync(path.join(P, 'index.ts'), 'utf8').matchAll(/export \{([^}]+)\} from '\.\/([^']+)'/g)) {
    for (const part of m[1].split(',').map((x) => x.trim()).filter(Boolean)) {
      const r = /^(\w+)\s+as\s+(\w+)$/.exec(part);
      names.push({ name: r ? r[2] : part, local: r ? r[1] : part, file: path.join(P, m[2]) });
    }
  }
  const byName = new Map(names.map((n) => [n.name, n]));
  const entry = Object.fromEntries(names.map((n) => [n.name, ENTRY + n.name]));
  entry.index = path.join(P, 'index.ts');
  entry['i18n/ar'] = path.join(P, 'i18n', 'ar.optin.ts');
  const entries = {
    name: 'plenix-entries',
    enforce: 'pre',
    // Vite's library mode resolves an entry against the root first, so the name may come with a folder in front of it
    resolveId(spec) { const i = spec.indexOf(ENTRY); return i >= 0 ? '\0' + spec.slice(i) : null; },
    load(id) {
      if (!id.startsWith('\0' + ENTRY)) return null;
      const n = byName.get(id.slice(ENTRY.length + 1));
      return 'export { ' + (n.local === n.name ? n.name : n.local + ' as ' + n.name) + " } from '" + n.file.split(path.sep).join('/') + "';\n";
    },
  };
  // each module's group, computed once when the chunks are made. The groups are layers (ORDER): a module's static imports
  // sit in its own layer or a lower one, so no two chunks import each other (a cycle can run code before what it needs)
  let groups = null;
  const assign = (api) => {
    const reached = (list) => {
      const seen = new Set(), stack = list.filter((n) => byName.has(n)).map((n) => '\0' + ENTRY + n);
      while (stack.length) {
        const id = stack.pop();
        if (seen.has(id)) continue;
        seen.add(id);
        const info = api.getModuleInfo(id);
        if (info) for (const d of info.importedIds) stack.push(d);
      }
      for (const id of [...seen]) if (id.startsWith('\0' + ENTRY)) seen.delete(id);
      return seen;
    };
    groups = new Map();
    // each layer takes what its parts reach that no lower layer holds. What a part reaches, its imports reach too, so a
    // layer's code imports only its own layer or a lower one, and no two chunks import each other
    for (const [layer, parts] of LAYERS) for (const id of reached(parts)) if (!groups.has(id)) groups.set(id, layer);
    // the rest (rarer parts, the page templates, commerce) is left to Rollup: each loads only what it uses
  };
  // a module that only a dynamic import() reaches has no group: it loads on first use, in a chunk of its own
  const group = (id, api) => { if (!groups) assign(api); return groups.get(id); };
  const base = packageConfig('esm', {});
  return Object.assign(base, {
    plugins: [entries, ...base.plugins],
    define: Object.assign({}, base.define, { 'process.env.NODE_ENV': JSON.stringify('production') }),
    build: Object.assign({}, base.build, {
      outDir: path.join(ROOT, 'release', 'cdn', VERSION, 'esm'),
      lib: { entry, formats: ['es'], fileName: (format, entryName) => entryName + '.js' },
      rollupOptions: {
        external: EXTERNAL,
        output: { banner: BANNER, chunkFileNames: 'chunks/[name]-[hash].js', manualChunks: group, minifyInternalExports: false },
      },
    }),
  });
}

export default defineConfig(() => (process.env.PLENIX_PACKAGE === 'cdnesm' ? cdnEsmConfig() : packageConfig(process.env.PLENIX_PACKAGE || 'esm')));
